"""$0 census for the dependency design review (D692): in the three finished poc-v118 draws (release comparison old-1..3), which
questions could be linked, and what the product already records about their relation.

Two sources are listed side by side, for every question the matcher opened as new:
  1. the matcher's own relation answers stored in the match record's reason ("v9: part_of 0.99"); the criterion is "one asks about a
     strict component or subset of the other, in either direction" (`jev_matching.RELATIONS`), so it carries no direction;
  2. the typed keys code already stores per question (`view_keys`: measure, scope, period), listed for every number question of the
     same company, so a reader can see which pairs share a period and how their measures relate.

  python3 selection_census.py > selection-census.md

The stores are opened read-only. Nothing is judged here: the lists are for the council to read.
"""
import json
import re
import sqlite3
from pathlib import Path

REPO = Path(__file__).resolve().parents[4]
RUNS = REPO / 'poc/data/comparison-2026-11-17/run'
THRESHOLD = 0.5                                        # jev_matching.THRESHOLD


def census(draw):
    conn = sqlite3.connect(f'file:{RUNS / draw}/prod/views.sqlite?mode=ro', uri=True)
    questions = dict(conn.execute('select view_id, question from views'))
    opened_at = {}
    for view_id, seq in conn.execute('select view_id, created_seq from views'):
        opened_at.setdefault(seq, []).append(view_id)
    keys = {row[0]: row for row in conn.execute('select view_id, measure, scope, period_start, period_end, unit from view_keys')}
    relations = []
    for seq, decisions in conn.execute('select seq, decisions_json from match_records order by seq, id'):
        data = json.loads(decisions or '{}')
        for candidate in (data.get('candidates', []) if isinstance(data, dict) else []):
            if candidate.get('outcome') != 'new':
                continue
            best = {}
            for other, probability in re.findall(r'(v\d+): part_of ([0-9.]+)', candidate.get('reason', '')):
                if float(probability) >= THRESHOLD:
                    best[other] = max(best.get(other, 0.0), float(probability))
            if best:
                relations.append({'seq': seq, 'opened': opened_at.get(seq, []), 'collision_judge_asked': 'collision judge' in candidate.get('reason', ''),
                                  'part_of': sorted(best.items(), key=lambda pair: -pair[1])})
    numbers = sorted((k for k in keys.values() if k[5] in ('USD', 'percent')), key=lambda k: (k[3] or '', k[1] or '', k[0]))
    return questions, keys, relations, numbers


def main():
    print('# Selection census for the dependency design review (D692), $0\n')
    print('Generated by `selection_census.py` from the three finished poc-v118 draws (`poc/data/comparison-2026-11-17/run/old-{1,2,3}`).')
    print('None of the three stores holds a dependency row (the Jev matcher returns `dependencies: []`, `jev_matching.py`).\n')
    for draw in ('old-1', 'old-2', 'old-3'):
        questions, keys, relations, numbers = census(draw)
        print(f'## {draw}\n')
        print(f'### The matcher\'s "part_of" answers (>= {THRESHOLD}) on questions it opened as new: {len(relations)} openings\n')
        print('| seq | opened | collision judge asked | part_of (other question, probability) |')
        print('|---|---|---|---|')
        for row in relations:
            listed = '; '.join(f'{other} {probability:.2f} "{questions.get(other, "?")[:70]}"' for other, probability in row['part_of'])
            opened = ', '.join(f'{v} "{questions.get(v, "?")[:60]}"' for v in row['opened'])
            print(f'| {row["seq"]} | {opened} | {row["collision_judge_asked"]} | {listed} |')
        print(f'\n### Number questions by typed key (measure, scope, period, unit): {len(numbers)}\n')
        print('| question | measure | scope | period | unit | text |')
        print('|---|---|---|---|---|---|')
        for view_id, measure, scope, start, end, unit in numbers:
            print(f'| {view_id} | {measure} | {scope} | {start}..{end} | {unit} | {questions.get(view_id, "?")[:90]} |')
        print()


if __name__ == '__main__':
    main()
