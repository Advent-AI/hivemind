"""Bundle the PRDs in docs/prd into docs/system-design/prd-bundle.js, so the design page can show them when it is opened
from disk (a browser refuses a page opened from disk to read other local files; served over HTTP the page reads the .md
files themselves).

    python3 docs/prd/build_bundle.py           # write the bundle
    python3 docs/prd/build_bundle.py --check   # exit 1 when the bundle does not match the .md files
"""

import json
import sys
from pathlib import Path

PRD_DIRECTORY = Path(__file__).resolve().parent
REPOSITORY = PRD_DIRECTORY.parents[1]
BUNDLE = REPOSITORY / "docs" / "system-design" / "prd-bundle.js"


def bundle_text():
    documents = {f"docs/prd/{path.name}": path.read_text(encoding="utf-8") for path in sorted(PRD_DIRECTORY.glob("*.md"))}
    if not documents:
        raise SystemExit(f"no .md files in {PRD_DIRECTORY}")
    body = json.dumps(documents, ensure_ascii=False, indent=1)
    return ("// Generated by docs/prd/build_bundle.py from docs/prd/*.md. Do not edit; edit the .md files and rerun it.\n"
            f"window.HIVEMIND_PRD = {body};\n"), len(documents)


def main():
    text, count = bundle_text()
    if "--check" in sys.argv[1:]:
        current = BUNDLE.read_text(encoding="utf-8") if BUNDLE.exists() else ""
        if current != text:
            print(f"STALE: {BUNDLE.relative_to(REPOSITORY)} does not match the {count} .md files; rerun without --check")
            return 1
        print(f"OK: the bundle matches the {count} .md files")
        return 0
    BUNDLE.write_text(text, encoding="utf-8")
    print(f"wrote {BUNDLE.relative_to(REPOSITORY)} with {count} PRDs")
    return 0


if __name__ == "__main__":
    sys.exit(main())
