"""Every failed mark and every named fault in the stored practice readings of the Stage A form, listed from the reader answers.

The design's account of a reading is an interpretation; this listing is the record it must agree with. It reads only files in
this folder and writes `readings_summary.md` beside itself.
Run: python3 clean-arch/step4-2026-11-10/readings_summary.py
"""
import collections
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
MARKS = ['Q', 'O', 'R', 'D', 'X', 'F', 'Y', 'G', 'L', 'XR', 'N']
READINGS = [   # folder, the reader files of the ladder form, the key file when one sits in the folder
    ('dryrun', ['reader-codex.jsonl', 'reader-claude.jsonl'], 'dryrun_key.json'),
    ('dryrun2', ['reader-codex-a.jsonl', 'reader-claude-a.jsonl', 'reader-codex-a2.jsonl'], 'dryrun2_key.json'),
    ('dryrun3', ['reader-codex.jsonl', 'reader-claude.jsonl'], 'key.json'),
    ('dryrun4', ['reader-codex.jsonl', 'reader-claude.jsonl'], 'key.json'),
    ('dryrun5', ['reader-codex.jsonl', 'reader-claude.jsonl'], 'key.json'),
    ('dryrun6', ['reader-codex.jsonl'], None),
    ('dryrun7', ['reader-codex.jsonl', 'reader-claude.jsonl'], None),
    ('dryrun8', ['reader-codex.jsonl', 'reader-claude.jsonl'], None),
    ('dryrun9', ['reader-codex.jsonl', 'reader-claude.jsonl'], None),
    ('dryrun10', ['reader-codex.jsonl', 'reader-claude.jsonl'], None),
    ('dryrun11', ['reader-codex.jsonl', 'reader-claude.jsonl'], None),
    ('dryrun12', ['reader-codex.jsonl', 'reader-claude.jsonl'], None),
]
REFERENCE_MARKS = ['ONE', 'O', 'R', 'D', 'X', 'F', 'Y', 'G']      # the marks both forms of the reference reading carry


def item_name(row):
    """An item's number, or the ladder's name in the side-by-side packet of the second reading."""
    if 'item' in row:
        return str(row['item'])
    return f"{row['thesis_id'].split()[0]} {row['ladder']}"


def planted_marks(folder, key_file):
    """item name -> the mark the key says a fault was planted under, or None; an empty dict when the key has another shape."""
    if key_file is None or not (HERE / folder / key_file).exists():
        return {}
    key = json.loads((HERE / folder / key_file).read_text())
    if folder == 'dryrun':
        return {item: entry['planted_mark'] for item, entry in key.items()}
    if folder == 'dryrun2':
        return {ladder: entry['planted_mark'] for ladder, entry in key['a'].items()}
    return {}


def reference_lines():
    """The 36 production ladders, read twice by each reader under two forms: how often a reader gave one mark the same value both
    times. The two forms differ in the due-day rule, so D's count compares two rules, not one rule read twice."""
    folder = HERE / 'reference'
    lines = ["## `reference/`: each reader's two readings of the 36 production ladders",
             'The second form changed the due-day rule (mark D); the other marks are worded alike in both forms.', '']
    for reader in ('codex', 'claude'):
        readings = []
        for file_name in (f'reader-{reader}.jsonl', f'reader-{reader}-2.jsonl'):
            rows = [json.loads(line) for line in (folder / file_name).read_text().splitlines() if line.strip()]
            readings.append({str(row['item']): row for row in rows})
        first, second = readings
        same = {mark: sum(1 for item in first if item in second and first[item].get(mark) == second[item].get(mark)) for mark in REFERENCE_MARKS}
        lines.append(f"- `reader-{reader}`: {len(first)} ladders; the same value in both readings: "
                     + ', '.join(f'{mark} {count}' for mark, count in same.items()))
        failed_second = {mark: sum(1 for row in second.values() if row.get(mark) == 'fails') for mark in REFERENCE_MARKS}
        named = sum(1 for row in second.values() if (row.get('W') or '').strip())
        lines.append(f"  - second form, ladders failing each mark: " + ', '.join(f'{mark} {count}' for mark, count in failed_second.items())
                     + f'; ladders with a fault named under W: {named}')
    lines.append('')
    return lines


def main():
    lines = ['# Practice readings of the Stage A form: every failed mark and every named fault (generated)', '',
             'Generated by `readings_summary.py` from the reader answers stored in this folder. Do not edit by hand.',
             'A row is listed when the reader failed a mark or named a fault under `W`; rows with neither are counted only.', '']
    for folder, reader_files, key_file in READINGS:
        if not (HERE / folder).exists():
            continue
        planted = planted_marks(folder, key_file)
        lines.append(f'## `{folder}/`')
        if planted:
            by_mark = collections.Counter(mark for mark in planted.values() if mark)
            unplanted = sum(1 for mark in planted.values() if not mark)
            lines.append(f"Key `{key_file}`: {sum(by_mark.values())} planted faults ("
                         + ', '.join(f'{mark} {count}' for mark, count in sorted(by_mark.items())) + f'), {unplanted} answers with none. '
                         + 'Marks with no planted fault: ' + (', '.join(mark for mark in MARKS if mark not in by_mark) or 'none') + '.')
        elif key_file:
            lines.append(f'Key `{key_file}` is in the folder; its shape is specific to this reading and is not read here.')
        else:
            lines.append('No key in the folder.')
        lines.append('')
        for reader_file in reader_files:
            path = HERE / folder / reader_file
            if not path.exists():
                lines.append(f'- `{reader_file}`: not on disk')
                continue
            rows = [json.loads(line) for line in path.read_text().splitlines() if line.strip()]
            listed = []
            caught = 0
            failed_on_unplanted = 0
            for row in rows:
                name = item_name(row)
                failed = [mark for mark in MARKS if row.get(mark) == 'fails']
                named_fault = (row.get('W') or '').strip()
                if planted:
                    mark = planted.get(name)
                    if mark and mark in failed:
                        caught += 1
                    if not mark and failed:
                        failed_on_unplanted += 1
                if failed or named_fault:
                    planted_note = f' (planted: {planted[name] or "none"})' if planted else ''
                    listed.append(f"  - item {name}{planted_note}: fails {', '.join(failed) or 'none'}"
                                  + (f'; W: {named_fault}' if named_fault else ''))
            summary = f'- `{reader_file}`: {len(rows)} rows, {len(listed)} with a failed mark or a named fault'
            if planted:
                total_planted = sum(1 for mark in planted.values() if mark)
                summary += f'; planted faults caught under their own mark: {caught} of {total_planted}; unplanted answers given a failed mark: {failed_on_unplanted}'
            lines.append(summary)
            lines.extend(listed)
        lines.append('')
    lines.extend(reference_lines())
    (HERE / 'readings_summary.md').write_text('\n'.join(lines) + '\n')
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
