"""Write fonts-embedded.css: the faces of fonts.css as data URIs, for a page opened from disk (file://), where the
browser refuses to load font files. Run it again after a font file changes:

    python3 web/design-system/embed_fonts.py
"""

import base64
from pathlib import Path

DESIGN_SYSTEM_DIRECTORY = Path(__file__).resolve().parent
FACES = [("Geist", "Geist-Variable.woff2"), ("Geist Mono", "GeistMono-Variable.woff2")]


def main():
    rules = ["/* Generated by embed_fonts.py from fonts/; do not edit by hand. The faces of fonts.css as data URIs. */"]
    for family, file_name in FACES:
        encoded = base64.b64encode((DESIGN_SYSTEM_DIRECTORY / "fonts" / file_name).read_bytes()).decode("ascii")
        rules.append(
            "@font-face {\n"
            f'  font-family: "{family}";\n'
            f'  src: url("data:font/woff2;base64,{encoded}") format("woff2");\n'
            "  font-weight: 100 900;\n"
            "  font-display: swap;\n"
            "}"
        )
    output_path = DESIGN_SYSTEM_DIRECTORY / "fonts-embedded.css"
    output_path.write_text("\n\n".join(rules) + "\n", encoding="ascii")
    print(f"wrote {output_path} ({output_path.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
